#!/usr/bin/env python3
"""Writes tests/layout/layout.c: a program printing the size, alignment and
field offsets of every struct in include/fsurf.h, which tests/host compares
with the Odin ABI package. Run it after changing the header."""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
def strip(name):
    return re.sub(r'/\*.*?\*/', '', (root / 'include' / name).read_text(), flags=re.S)
h = strip('fsurf.h') + strip('fsurf_daw.h') + strip('fsurf_layout.h')
out = ['/* Prints the layout of fsurf.h\'s structs. Generated by scripts/gen_layout.py. */',
       '#include <stdio.h>', '#include <stddef.h>', '#include "fsurf.h"', '#include "fsurf_daw.h"', '#include "fsurf_layout.h"',
       '#define S(t) printf("%s size %zu align %zu\\n", #t, sizeof(t), _Alignof(t));',
       '#define F(t, f) printf("%s.%s %zu\\n", #t, #f, offsetof(t, f));',
       'int main(void) {']
for tag, body, td in re.findall(r'typedef struct (\w+) \{(.*?)\n\} (\w+);', h, re.S):
    out.append(f'\tS({td})')
    for decl in body.split(';'):
        decl = re.sub(r'\[.*?\]', '', ' '.join(decl.split()))
        if not decl:
            continue
        fn = re.match(r'.*\(\*(\w+)\)\(', decl)
        if fn:
            names = [fn.group(1)]
        else:  # "float x, y, w, h": each
            parts = [p.strip() for p in decl.split(',')]
            names = [re.findall(r'(\w+)$', parts[0])[0]] + parts[1:]
        for name in names:
            out.append(f'\tF({td}, {name})')
# The extension's enumerators, to check against the Odin enums.
for body in re.findall(r'enum \{(.*?)\};', strip('fsurf.h') + strip('fsurf_daw.h') + strip('fsurf_layout.h'), re.S):
    for item in body.split(','):
        name = item.split('=')[0].strip()
        if name.startswith(('FSURF_DAW_', 'FSURF_LAYOUT_', 'FSURF_PIXEL_', 'FSURF_DEVICE_')):
            out.append(f'\tprintf("E {name} %d\\n", (int){name});')
out.append('\treturn 0;\n}')
(root / 'tests/layout/layout.c').write_text('\n'.join(out) + '\n')
