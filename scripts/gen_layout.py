#!/usr/bin/env python3
"""Writes tests/layout/layout.c: a program printing the size, alignment and
field offsets of every struct in include/fsurf.h, which tests/host compares
with the Odin ABI package. Run it after changing the header."""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
h = re.sub(r'/\*.*?\*/', '', (root / 'include/fsurf.h').read_text(), flags=re.S)
out = ['/* Prints the layout of fsurf.h\'s structs. Generated by scripts/gen_layout.py. */',
       '#include <stdio.h>', '#include <stddef.h>', '#include "fsurf.h"',
       '#define S(t) printf("%s size %zu align %zu\\n", #t, sizeof(t), _Alignof(t));',
       '#define F(t, f) printf("%s.%s %zu\\n", #t, #f, offsetof(t, f));',
       'int main(void) {']
for tag, body, td in re.findall(r'typedef struct (\w+) \{(.*?)\n\} (\w+);', h, re.S):
    out.append(f'\tS({td})')
    for decl in body.split(';'):
        decl = re.sub(r'\[.*?\]', '', ' '.join(decl.split()))
        if not decl:
            continue
        fn = re.match(r'.*\(\*(\w+)\)\(', decl)
        name = fn.group(1) if fn else re.findall(r'(\w+)$', decl)[0]
        out.append(f'\tF({td}, {name})')
out.append('\treturn 0;\n}')
(root / 'tests/layout/layout.c').write_text('\n'.join(out) + '\n')
